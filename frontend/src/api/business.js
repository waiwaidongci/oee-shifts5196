import {request} from './client.js';
export const loadAll=async()=>Object.fromEntries(await Promise.all([['sources','/sources'],['periods','/periods'],['policies','/policies'],['runs','/runs'],['schedules','/schedules'],['deliveries','/deliveries'],['audits','/audits'],['reconBatches','/reconcile/batches']].map(async([k,path])=>[k,await request(path)])));
export const saveSource=(data,id)=>request('/sources'+(id?'/'+id:''),id?'PUT':'POST',{data});
export const savePolicy=data=>request('/policies','POST',{data});
export const submitRun=data=>request('/runs','POST',data);
export const approveRun=(id,note)=>request('/runs/'+id+'/approve','POST',{note});
export const reconPool=runId=>request('/reconcile/pool/'+runId);
export const reconPreview=body=>request('/reconcile/preview','POST',body);
export const reconConfirm=body=>request('/reconcile/confirm','POST',body);
export const reconBatch=id=>request('/reconcile/batches/'+id);
